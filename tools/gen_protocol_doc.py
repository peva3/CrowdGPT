#!/usr/bin/env python3
"""Generate docs/NG_PROTOCOL.md from crowdgpt_ng.protocol dataclasses."""
from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import crowdgpt_ng.protocol as p  # noqa: E402

CLASSES = [p.Ticket, p.StepReceipt, p.EvalResult, p.CheckpointRef, p.NodeRecord, p.RoundRecord]


def type_name(value):
    return getattr(value, "__name__", str(value))


def main():
    print("# NG protocol specification")
    print()
    print("Generated by `tools/gen_protocol_doc.py`. Do not edit by hand.")
    print()
    print("Schema version: `ng-1`. Wire tickets use `ng-ticket-1`. Legacy")
    print("round exports use `ng-legacy-1`; eval manifests use `ng-eval-1`.")
    print()
    print("## Wire rules")
    print()
    print("- Canonical JSON: UTF-8, sorted keys, compact separators `(',', ':')`,")
    print("  no NaN or Infinity. Digests are SHA-256 over canonical bytes.")
    print("- Losses are fixed six-place decimal **strings**, never floats.")
    print("- Ed25519 detached signatures cover the canonical bytes of the")
    print("  object's `signing_payload()`. Certificates are excluded from that")
    print("  payload and attached with `with_certificate`.")
    print("- Merkle roots are sorted-leaf SHA-256 roots with duplicate-last")
    print("  promotion. Inclusion proofs are verified against the root.")
    print("- Unknown fields are rejected. A schema change that adds a required")
    print("  field bumps the schema version; additive optional fields do not.")
    print()
    print("## Compatibility")
    print()
    print("Readers accept only the current schema version. Writers must emit")
    print("every required field. A record with an unknown version is rejected,")
    print("not silently downgraded. `RoundRecord.hash()` is content-addressed")
    print("and independent of the certificate.")
    print()
    for cls in CLASSES:
        print(f"## `{cls.__name__}`")
        print()
        print("| field | type | required |")
        print("|---|---|---|")
        for field in dataclasses.fields(cls):
            required = field.default is dataclasses.MISSING and \
                field.default_factory is dataclasses.MISSING
            print(f"| `{field.name}` | `{type_name(field.type)}` | "
                  f"{'yes' if required else 'no'} |")
        print()
    print("## Versioning")
    print()
    print("- `ng-1`: round records, node records, receipts, checkpoints, evals.")
    print("- `ng-ticket-1`: signed admission tickets.")
    print("- `ng-legacy-1`: imported pre-NG round snapshots.")
    print("- `ng-eval-1`: held-out eval manifest.")
    print()
    print("A change to canonical encoding, signature scope, or a required field")
    print("is breaking: bump the version and keep a reader for the old one until")
    print("every published record has aged out.")


if __name__ == "__main__":
    main()
